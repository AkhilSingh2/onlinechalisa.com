const MAPS: Record<Exclude<Script, 'devanagari' | 'iast'>, Record<string, string>> = {
  telugu: deva_to_telugu,
  kannada: deva_to_kannada,
  tamil: deva_to_tamil,
  bengali: deva_to_bengali,
};

/**
 * Transliterate Devanagari text to the target Indic script.
 * Unmapped characters (Latin, punctuation, whitespace) pass through.
 */
export function transliterate(text: string, target: Script): string {
  if (target === 'devanagari' || target === 'iast') return text;
  const map = MAPS[target];
  if (!map) return text;
  let out = '';
  // Iterate by Unicode code point (Devanagari nukta forms are BMP,
  // but we're future-proof).
  for (const ch of text) {
    out += map[ch] ?? ch;
  }
  return out;
}
