// Spoken-recitation generator.
// Sends each verse, as one request, to an ElevenLabs Hindi voice. Caches one
// clip per verse, joins them with a pause between verses, and writes:
//   public/audio/<slug>.mp3   — the full paath (mono, 96 kbps)
//   public/audio/<slug>.json  — per-verse start/end times for the reader
//
//   npm run audio -- hanuman            generate (re-uses cached verses)
//   npm run audio -- hanuman --redo 7   regenerate verse index 7 only
//   npm run audio -- --all              every chalisa
//
// Needs ELEVENLABS_API_KEY and ELEVENLABS_VOICE_ID in .env, and ffmpeg
// + ffprobe on PATH (override with FFMPEG / FFPROBE).
import { createHash } from 'node:crypto';
import { existsSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { spawnSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const __dirname = dirname(fileURLToPath(import.meta.url));
const root = join(__dirname, '..');
// Chalisas, and paath (bhajans, kavach, ashtak). `--all` covers chalisas only;
// paath texts are generated by naming their slug.
const contentDir = join(root, 'src/content/chalisas');
const paathDir = join(root, 'src/content/paath');
const outDir = join(root, 'public/audio');
const cacheRoot = join(root, '.audio-cache');

loadDotEnv(join(root, '.env'));

const API_KEY = process.env.ELEVENLABS_API_KEY;
const VOICE_ID = process.env.ELEVENLABS_VOICE_ID;
const MODEL_ID = process.env.ELEVENLABS_MODEL_ID || 'eleven_multilingual_v2';
const FFMPEG = process.env.FFMPEG || 'ffmpeg';
const FFPROBE = process.env.FFPROBE || 'ffprobe';

// Approved settings ("variant A"): whole-verse requests with expression on.
const VOICE_SETTINGS = {
  stability: 0.5,
  similarity_boost: 0.8,
  style: 0.35,
  use_speaker_boost: true,
  speed: 0.9,
};

// Silence after a finished verse.
const PAUSE_AFTER = { doha: 0.9, sortha: 0.9, chaupai: 0.45 };
const LEAD_IN = 0.4;
const SAMPLE_RATE = 44100;

const args = process.argv.slice(2);
const redo = new Set();
const slugs = [];
for (let i = 0; i < args.length; i++) {
  if (args[i] === '--redo') redo.add(Number(args[++i]));
  else if (args[i] === '--all') slugs.push(...allSlugs());
  else slugs.push(args[i]);
}

if (slugs.length === 0) fail('Usage: npm run audio -- <slug> [--redo <verseIndex>] | --all');
if (!API_KEY || !VOICE_ID) fail('Set ELEVENLABS_API_KEY and ELEVENLABS_VOICE_ID in .env');
for (const bin of [FFMPEG, FFPROBE]) {
  if (spawnSync(bin, ['-version']).status !== 0) fail(`${bin} not found on PATH`);
}

mkdirSync(outDir, { recursive: true });

async function generate(slug) {
  const file = [join(contentDir, `${slug}.json`), join(paathDir, `${slug}.json`)].find(existsSync);
  if (!file) fail(`No chalisa or paath named "${slug}" in src/content`);
  const { verses } = JSON.parse(readFileSync(file, 'utf8'));

  const cacheDir = join(cacheRoot, slug);
  mkdirSync(cacheDir, { recursive: true });

  console.log(`\n${slug}: ${verses.length} verses`);
  const clips = [];
  for (let i = 0; i < verses.length; i++) {
    const text = speakable(verses[i].hi);
    const hash = createHash('sha1')
      .update(JSON.stringify({ text, VOICE_ID, MODEL_ID, VOICE_SETTINGS }))
      .digest('hex')
      .slice(0, 10);
    const clip = join(cacheDir, `${i}-${hash}.mp3`);
    if (redo.has(i) || !existsSync(clip)) {
      for (const stale of readdirSync(cacheDir).filter((f) => f.startsWith(`${i}-`))) {
        rmSync(join(cacheDir, stale));
      }
      process.stdout.write(`  verse ${i}: generating… `);
      writeFileSync(clip, await tts(text));
      console.log('done');
    } else {
      console.log(`  verse ${i}: cached`);
    }
    clips.push(clip);
  }

  // Normalise every clip to the same PCM format and append its pause, so
  // the concat is sample-accurate and timings come from exact WAV lengths.
  const workDir = join(cacheDir, '.work');
  rmSync(workDir, { recursive: true, force: true });
  mkdirSync(workDir);

  const lead = join(workDir, 'lead.wav');
  run(FFMPEG, ['-f', 'lavfi', '-i', `anullsrc=r=${SAMPLE_RATE}:cl=mono`, '-t', String(LEAD_IN), lead]);

  const segments = [lead];
  const timings = [];
  let cursor = LEAD_IN;
  for (let i = 0; i < clips.length; i++) {
    const voiced = join(workDir, `${i}.wav`);
    trim(clips[i], voiced);
    const spoken = duration(voiced);
    const pause = i === clips.length - 1 ? 0 : (PAUSE_AFTER[verses[i].type] ?? PAUSE_AFTER.chaupai);
    const padded = join(workDir, `${i}-padded.wav`);
    // Fade the tail into the verse pause so the splice is not a click.
    run(FFMPEG, ['-i', voiced, '-af', `areverse,afade=t=in:d=0.12:curve=desi,areverse,apad=pad_dur=${pause}`, padded]);
    timings.push({ i, start: round(cursor), end: round(cursor + spoken) });
    cursor += duration(padded);
    segments.push(padded);
  }

  const list = join(workDir, 'list.txt');
  writeFileSync(list, segments.map((s) => `file '${s.replace(/'/g, "'\\''")}'`).join('\n'));
  const mp3 = join(outDir, `${slug}.mp3`);
  run(FFMPEG, [
    '-f', 'concat', '-safe', '0', '-i', list,
    '-af', 'loudnorm=I=-18:TP=-1.5:LRA=11',
    '-ac', '1', '-ar', String(SAMPLE_RATE), '-b:a', '96k', '-y', mp3,
  ]);
  rmSync(workDir, { recursive: true, force: true });

  const total = duration(mp3);
  writeFileSync(
    join(outDir, `${slug}.json`),
    JSON.stringify({ slug, duration: round(total), verses: timings }, null, 2) + '\n',
  );
  console.log(`  wrote public/audio/${slug}.mp3 (${Math.floor(total / 60)}m ${Math.round(total % 60)}s) and ${slug}.json`);
}

// Keep the danda (।) and the verse end (॥ read as।): the model reads them as
// natural phrase ends. A line break becomes a space so the verse is one phrase.
function speakable(hi) {
  return hi.replace(/॥/g, '।').replace(/\s*\n+\s*/g, ' ').trim();
}

// Remove leading and trailing silence from a clip.
function trim(src, dest) {
  const cut = 'silenceremove=start_periods=1:start_silence=0.03:start_threshold=-42dB';
  run(FFMPEG, [
    '-i', src, '-ac', '1', '-ar', String(SAMPLE_RATE),
    '-af', `${cut},areverse,${cut},areverse,afade=t=in:d=0.03:curve=desi`,
    dest,
  ]);
}

async function tts(text) {
  const url = `https://api.elevenlabs.io/v1/text-to-speech/${VOICE_ID}?output_format=mp3_44100_128`;
  for (let attempt = 1; ; attempt++) {
    const res = await fetch(url, {
      method: 'POST',
      headers: { 'xi-api-key': API_KEY, 'Content-Type': 'application/json', Accept: 'audio/mpeg' },
      body: JSON.stringify({
        text,
        model_id: MODEL_ID,
        voice_settings: VOICE_SETTINGS,
      }),
    });
    if (res.ok) return Buffer.from(await res.arrayBuffer());
    const body = await res.text();
    if ((res.status === 429 || res.status >= 500) && attempt < 4) {
      await new Promise((r) => setTimeout(r, attempt * 3000));
      continue;
    }
    fail(`ElevenLabs ${res.status}: ${body}`);
  }
}

function duration(file) {
  const r = spawnSync(FFPROBE, [
    '-v', 'error', '-show_entries', 'format=duration', '-of', 'default=nw=1:nk=1', file,
  ]);
  if (r.status !== 0) fail(`ffprobe failed on ${file}: ${r.stderr}`);
  return parseFloat(String(r.stdout).trim());
}

function run(bin, argv) {
  const r = spawnSync(bin, ['-hide_banner', '-loglevel', 'error', '-y', ...argv]);
  if (r.status !== 0) fail(`${bin} ${argv.join(' ')}\n${r.stderr}`);
}

function allSlugs() {
  return readdirSync(contentDir)
    .filter((f) => f.endsWith('.json'))
    .map((f) => f.replace(/\.json$/, ''));
}

function loadDotEnv(path) {
  if (!existsSync(path)) return;
  for (const line of readFileSync(path, 'utf8').split('\n')) {
    const m = line.match(/^\s*([A-Z0-9_]+)\s*=\s*(.*?)\s*$/);
    if (m && !(m[1] in process.env)) process.env[m[1]] = m[2].replace(/^(['"])(.*)\1$/, '$2');
  }
}

function round(n) {
  return Math.round(n * 1000) / 1000;
}

function fail(msg) {
  console.error(msg);
  process.exit(1);
}

for (const slug of slugs) await generate(slug);
